export function I18nProvider({ children }: { children: ReactNode }) {
  // SSR renders English; the stored choice applies after hydration.
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "km" || stored === "en") setLangState(stored);
  }, []);

  // Keep the document language honest — screen readers and the :lang(km)
  // line-height rule both depend on it.
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  };

  const t = (key: I18nKey) => dictionaries[lang][key] ?? en[key];

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

/** Exported for tests: every key present in both dictionaries. */
export const _dictionaries = dictionaries;

// Chromium builds without Khmer ICU data silently fall back to English for
// km-KH dates, so month names are spelled out here instead of trusting Intl.
const KHMER_MONTHS = [
  "មករា", "កុម្ភៈ", "មីនា", "មេសា", "ឧសភា", "មិថុនា",
  "កក្កដា", "សីហា", "កញ្ញា", "តុលា", "វិច្ឆិកា", "ធ្នូ",
];

/** Long date in the active language, e.g. "15 សីហា 2026" / "15 August 2026". */
export function formatLongDate(d: Date, lang: Lang): string {
  if (lang === "km") return `${d.getDate()} ${KHMER_MONTHS[d.getMonth()]} ${d.getFullYear()}`;
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}
